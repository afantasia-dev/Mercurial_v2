// 5. RUTINAS DE DIBUJADO DE CAJAS
// ==========================================
void dibujar_interfaz() {
    uint8_t tile;
    uint8_t x = 1, y = 1, w = 30, h = 28;
    uint8_t i; 

    tile = 110; set_bkg_tiles(x, y, 1, 1, &tile);
    tile = 111; set_bkg_tiles(x+w-1, y, 1, 1, &tile);
    tile = 112; set_bkg_tiles(x, y+h-1, 1, 1, &tile);
    tile = 113; set_bkg_tiles(x+w-1, y+h-1, 1, 1, &tile);

    for(i = x + 1; i < x + w - 1; i++) {
        tile = 114; set_bkg_tiles(i, y, 1, 1, &tile);
        tile = 115; set_bkg_tiles(i, y+h-1, 1, 1, &tile);
    }
    for(i = y + 1; i < y + h - 1; i++) {
        tile = 116; set_bkg_tiles(x, i, 1, 1, &tile);
        tile = 117; set_bkg_tiles(x+w-1, i, 1, 1, &tile);
    }

    tile = 110; set_bkg_tiles(x, 4, 1, 1, &tile);
    tile = 111; set_bkg_tiles(x+w-1, 4, 1, 1, &tile);
    for(i = x + 1; i < x + w - 1; i++) {
        tile = 114; set_bkg_tiles(i, 4, 1, 1, &tile);
    }

    tile = 110; set_bkg_tiles(x, 24, 1, 1, &tile);
    tile = 111; set_bkg_tiles(x+w-1, 24, 1, 1, &tile);
    for(i = x + 1; i < x + w - 1; i++) {
        tile = 114; set_bkg_tiles(i, 24, 1, 1, &tile);
    }
}


// ==========================================
// 6. MOTOR ENIGMA
// ==========================================
void inicializar_enigma() {
    uint8_t i;
    for(i = 0; i < 32; i++) {
        INV_R1[ROTOR_1[i]] = i; 
        INV_R2[ROTOR_2[i]] = i; 
        INV_R3[ROTOR_3[i]] = i;
    }
}

uint8_t enigma_cifrar_letra(uint8_t letra) {
    letra = (ROTOR_1[(letra + perillas[0]) % 32] - perillas[0] + 32) % 32;
    letra = (ROTOR_2[(letra + perillas[1]) % 32] - perillas[1] + 32) % 32;
    letra = (ROTOR_3[(letra + perillas[2]) % 32] - perillas[2] + 32) % 32;
    
    letra = 31 - letra; 
    
    letra = (INV_R3[(letra + perillas[2]) % 32] - perillas[2] + 32) % 32;
    letra = (INV_R2[(letra + perillas[1]) % 32] - perillas[1] + 32) % 32;
    letra = (INV_R1[(letra + perillas[0]) % 32] - perillas[0] + 32) % 32;
    return letra;
}

// ==========================================
// 7. BUCLE PRINCIPAL MERCURIAL NES
// ==========================================
void main(void)
{
    uint8_t input_actual = 0, input_anterior = 0;
    uint8_t boton_presionado;
    uint8_t mostrar_cifrado = 0; 
    uint8_t estado_anterior = 255; 
    uint8_t i, col, row, x_pos, y_pos, letra_final, base_tile;
    uint8_t metasprite[4]; // Usado para ensamblar los bloques de 2x2 tiles

    inicializar_enigma();

    set_bkg_data(110, 8, BORDER_TILES);
    cargar_banco_activo(0);

    dibujar_interfaz();

    gotoxy(9, 2); 
    printf("MERCURIAL NES");
	
    gotoxy(9, 25);
    imprimirCorchete(perillas[0]);
    printf(" "); // Espacio separador
    imprimirCorchete(perillas[1]);
    printf(" "); // Espacio separador
    imprimirCorchete(perillas[2]);
	
    SHOW_BKG; 
    DISPLAY_ON;

    while(1) 
    {
        input_anterior = input_actual;
        input_actual = joypad();
        boton_presionado = (input_actual ^ input_anterior) & input_actual;

        // Modo de cifrado dinámico tipo HOLD
        mostrar_cifrado = (input_actual & J_A) ? 1 : 0;

        if (boton_presionado & J_LEFT) {
            perilla_seleccionada--;
            if(perilla_seleccionada < 0) perilla_seleccionada = 2; 
        }
        if (boton_presionado & J_RIGHT) {
            perilla_seleccionada++;
            if(perilla_seleccionada > 2) perilla_seleccionada = 0; 
        }
        if (boton_presionado & J_UP) {
            perillas[perilla_seleccionada] = (perillas[perilla_seleccionada] + 1) % 32; 
        }
        if (boton_presionado & J_DOWN) {
            perillas[perilla_seleccionada] = (perillas[perilla_seleccionada] - 1 + 32) % 32;
        }

        if(boton_presionado != 0 || mostrar_cifrado != estado_anterior || estado_anterior == 255) {
            
            if(mostrar_cifrado != estado_anterior) {
                cargar_banco_activo(mostrar_cifrado);
            }

            // REDISEÑO MATRICIAL (Escalado de 16x16 por Letra)
            for(i = 0; i < 32; i++) {
                col = i % 8;
                row = i / 8;
                
                // Centrado en el marco (dejamos espaciado de 3 tiles: 2 de letra + 1 vacío de separación)
                x_pos = 5 + (col * 3); 
                y_pos = 8 + (row * 3); 

                if (mostrar_cifrado) {
                    letra_final = enigma_cifrar_letra(i);
                } else {
                    letra_final = i;
                }
                
                // En vez de un solo tile de 8x8, ahora preparamos un metasprite de 2x2
                base_tile = 128 + (letra_final * 4); // Porque cada caracter ocupa 4 posiciones de memoria ahora
                metasprite[0] = base_tile;     // Top-Left
                metasprite[1] = base_tile + 1; // Top-Right
                metasprite[2] = base_tile + 2; // Bottom-Left
                metasprite[3] = base_tile + 3; // Bottom-Right

                // Dibujar bloque completo en el Background
                set_bkg_tiles(x_pos, y_pos, 2, 2, metasprite);
            }
        }

        // --- ACTUALIZACIÓN DE LA UI INFERIOR ---
        gotoxy(9, 25);
		imprimirCorchete(perillas[0]);
		printf(" "); // Espacio separador
		imprimirCorchete(perillas[1]);
		printf(" "); // Espacio separador
		imprimirCorchete(perillas[2]);
        
        gotoxy(9, 26); 
        if (perilla_seleccionada == 0)      printf("  ^           ");
        else if (perilla_seleccionada == 1) printf("       ^      ");
        else                                printf("            ^ ");

        gotoxy(7, 27); 
        if (mostrar_cifrado) printf("[ MODO: CIFRADO  ]");
        else                 printf("[ MODO: ORIGINAL ]");
        
        estado_anterior = mostrar_cifrado;
        vsync(); 
    }
}
