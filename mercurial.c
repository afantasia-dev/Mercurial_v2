// ==========================================
// 4. MOTOR DE ESCALADO DINÁMICO (8x8 -> 16x16)
// ==========================================
const uint8_t DOUBLE_BITS[16] = {
    0x00, 0x03, 0x0C, 0x0F, 0x30, 0x33, 0x3C, 0x3F, 
    0xC0, 0xC3, 0xCC, 0xCF, 0xF0, 0xF3, 0xFC, 0xFF
};

// Esta función lee un bloque de 16 bytes de tu FONT_0 o FONT_1 y lo convierte en 4 bloques (64 bytes)
void escalar_y_cargar_fuente(uint8_t id_destino_base, const uint8_t *origen) {
    uint8_t vram_data[64];
    uint8_t row, lsb, msb, left_lsb, left_msb, right_lsb, right_msb;
    uint8_t offset_tile_y, fila_interna;

    for (row = 0; row < 8; row++) {
        lsb = origen[row * 2];
        msb = origen[row * 2 + 1];

        // Duplicación matemática de los bits izquierdos y derechos
        left_lsb = DOUBLE_BITS[lsb >> 4];
        right_lsb = DOUBLE_BITS[lsb & 0x0F];
        left_msb = DOUBLE_BITS[msb >> 4];
        right_msb = DOUBLE_BITS[msb & 0x0F];

        // Decidimos si escribimos en la mitad superior o inferior del metasprite (2x2)
        offset_tile_y = (row < 4) ? 0 : 32;
        fila_interna = (row % 4) * 4;

        // Tile Izquierdo Superior/Inferior
        vram_data[offset_tile_y + fila_interna + 0] = left_lsb;
        vram_data[offset_tile_y + fila_interna + 1] = left_msb;
        vram_data[offset_tile_y + fila_interna + 2] = left_lsb; // Duplica línea visualmente
        vram_data[offset_tile_y + fila_interna + 3] = left_msb;

        // Tile Derecho Superior/Inferior
        vram_data[offset_tile_y + 16 + fila_interna + 0] = right_lsb;
        vram_data[offset_tile_y + 16 + fila_interna + 1] = right_msb;
        vram_data[offset_tile_y + 16 + fila_interna + 2] = right_lsb; // Duplica línea visualmente
        vram_data[offset_tile_y + 16 + fila_interna + 3] = right_msb;
    }
    
    // Sube el bloque escalado a la tarjeta de video de la NES
    set_bkg_data(id_destino_base, 4, vram_data);
}

// Carga todas las letras al instante
void cargar_banco_activo(uint8_t usar_cifrado) {
    uint8_t i;
    for(i = 0; i < 32; i++) {
        if(usar_cifrado) {
            escalar_y_cargar_fuente(128 + (i * 4), FONT_1[i]);
        } else {
            escalar_y_cargar_fuente(128 + (i * 4), FONT_0[i]);
        }
    }
}

